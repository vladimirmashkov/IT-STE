"""Generate a derived DRAFT, never an independently editable standard.

Only docs/IT-STE-draft.md is an accepted output path. check compares exact bytes
without writing; build refuses unrelated existing files and symlink aliases.
"""

from __future__ import annotations

import argparse
import hashlib
import importlib
import json
import re
import string
import sys
from pathlib import Path

if __package__:
    from . import it_ste_corpus as corpus
else:
    import it_ste_corpus as corpus

ROOT = corpus.ROOT
DEFAULT_OUTPUT = Path("docs/IT-STE-draft.md")
DEFAULT_BATCH = Path("standards/it-ste/vocabulary-reviews/asd-ste100/issue-9/r0001/batch-001.json")
BANNER = "# IT-STE — DRAFT\n\nGenerated by tools/it_ste_document.py. DO NOT EDIT.\n"


class DocumentError(RuntimeError):
    """Invalid inputs, unsafe output, or a stale generated snapshot."""


def escaped(value):
    """Display arbitrary source text as text rather than Markdown or HTML."""
    return re.sub(r"([" + re.escape(string.punctuation) + r"])", r"\\\1", str(value))


def fenced(value):
    fence = "`" * max(3, max((len(m[0]) + 1 for m in re.finditer(r"`+", value)), default=3))
    return f"{fence}\n{value}" + ("" if value.endswith("\n") else "\n") + fence


def metadata(value):
    return fenced(json.dumps(value, ensure_ascii=False, indent=2, sort_keys=True))


def example(segments):
    # Fencing the complete joined example preserves adjacency and all literal
    # whitespace when inline code would normalize it or backticks could collide.
    if any("\n" in s["text"] or "\r" in s["text"] or
           (s["kind"] == "literal" and ("`" in s["text"] or
            s["text"] != s["text"].strip())) for s in segments):
        return fenced("".join(s["text"] for s in segments))
    return "".join(f'`{s["text"]}`' if s["kind"] == "literal" else escaped(s["text"])
                   for s in segments)


def render():
    """Validate authoritative inputs before rendering deterministic UTF-8 bytes."""
    vocabulary = importlib.import_module(
        f"{__package__}.it_ste_vocabulary" if __package__ else "it_ste_vocabulary")
    count = corpus.check()
    batches, summary = vocabulary.checked_all()
    manifest_path = ROOT / corpus.DEFAULT_MANIFEST
    manifest = corpus.load_json(manifest_path)

    snapshot = manifest_path.parent
    records = [corpus.load_json(snapshot / name) for name in manifest["records"]]
    rules = [record for name, record in zip(manifest["records"], records) if "/rules/" in name]
    terms = [record for name, record in zip(manifest["records"], records) if "/terms/" in name]
    if (count != len(rules) or len(rules) != 31
            or any(record["status"] != "draft" for record in rules + terms)):
        raise DocumentError("Expected all 31 DRAFT rules and draft terms")
    lines = [BANNER, (f"> DRAFT: all {len(rules)} rules and {len(terms)} canonical IT-only terms require human review. "
             "This is not a release, a complete vocabulary, a conformance checker, or official ASD guidance."),
             "Edit canonical records and the vocabulary batches, then rebuild; never edit this snapshot.",
             f"Version: {escaped(manifest['version'])}; revision: {escaped(manifest['revision'])}.",
             "## Contents"]
    for rule in rules:
        lines.append(f"- [{rule['id']}](#{rule['id'].lower()}) — {escaped(rule['title'])}")
    if terms:
        lines.append("- [Canonical draft terms](#canonical-draft-terms)")
    lines += ["- [Vocabulary candidates](#vocabulary-candidates)",
              "- [Snapshot provenance](#snapshot-provenance)"]
    for rule in rules:
        lines += [f"## {rule['id']}", f"### {escaped(rule['title'])}", escaped(rule["text"]),
                  "Applies to: " + ", ".join(escaped(v) for v in rule["applies_to"]), "### Exceptions"]
        lines += ["- " + escaped(v) for v in rule["exceptions"]] or ["None."]
        for key, title in (("allowed", "Positive examples"), ("not_allowed", "Negative examples")):
            lines.append(f"### {title}")
            for item in rule["examples"][key]:
                lines += [example(item["segments"]), "Rationale: " + escaped(item["rationale"])]
        lines.append("Supporting rules: " + (", ".join(
            f"[{identifier}](#{identifier.lower()})" for identifier in rule["supporting_target_ids"])
            or "None."))
        lines += ["### Provenance and review",
                  ("Source: ASD-STE100 Issue 9; locators below use physical PDF pages. "
                  "Facet dispositions describe adaptations, not source approval."),
                  metadata({k: rule[k] for k in ("source_refs", "review", "rights")})]
    if terms:
        lines += ["## Canonical draft terms",
                  ("These original IT-STE term records are draft and sense/POS-bound. "
                   "Their external source metadata is not ASD provenance; human review remains required.")]
        for term in terms:
            lines += [f"### {term['id']}",
                      f"Term: {escaped(term['term'])}; POS: {escaped(term['part_of_speech'])}.",
                      "Definition: " + escaped(term["definition"]),
                      "Usage: " + escaped(term["usage"]),
                      "Domains: " + ", ".join(escaped(value) for value in term["domains"]),
                      "Rationale: " + escaped(term["rationale"])]
            for key, title in (("allowed", "Positive examples"), ("not_allowed", "Negative examples")):
                lines.append(f"### {title}")
                for item in term["examples"][key]:
                    lines += [escaped(item["text"]), "Rationale: " + escaped(item["rationale"])]
            lines += ["### Provenance and review",
                      "External reference metadata is evidence for the draft IT sense, not ASD provenance.",
                      metadata({k: term[k] for k in ("source_refs", "review", "rights")})]
    lines += ["## Vocabulary candidates",
              (f"First {summary['candidates']} source rows across {summary['batch_count']} batches; "
              f"{summary['remaining']} pending of {summary['total']} source rows. "
              "These are draft sense-level "
              "candidate dispositions, NOT an approved allowed/prohibited dictionary. "
              "They are distinct from canonical rules; examples do not admit vocabulary."),
              "Validated aggregate counts (structure and provenance only; no vocabulary approval):",
              metadata(summary)]
    batch_paths = []
    for batch in batches:
        batch_path = ROOT / vocabulary.DEFAULT_BATCH.parent / f"batch-{batch['batch_id']}.json"
        batch_paths.append(batch_path)
        lines += [f"### Batch {escaped(batch['batch_id'])}",
                  "Batch interpretation:", metadata(batch["interpretation"]),
                  "Batch source, sequence, domain registry, rights, and review metadata:",
                  metadata({k: v for k, v in batch.items()
                            if k not in ("decisions", "interpretation")})]
        for item in batch["decisions"]:
            lines += [f"### {item['entry_id']}",
                      f"Term: {escaped(item['headword'])}; POS: {escaped(item['part_of_speech_as_extracted'])}.",
                      (f"Status: {escaped(item['status'])}; {escaped(item['review_status'])}; "
                      f"candidate disposition: {escaped(item['it_disposition'])}."),
                      "Definition: " + escaped(item["it_definition"]),
                      "Domains: " + ", ".join(escaped(v) for v in item["domains"]),
                      "Rationale: " + escaped(item["rationale"]), "Contextual alternatives:"]
            lines += ["- " + escaped(v) for v in item["permitted_contextual_alternatives"]] or ["None."]
            for key in ("positive", "problematic"):
                lines += [f"#### {key.capitalize()} example", fenced(item["examples"][key]["text"]),
                          "Explanation: " + escaped(item["examples"][key]["explanation"])]
            lines += ["Source: ASD-STE100 Issue 9; raw mechanical status is not IT approval.",
                      metadata({k: item[k] for k in ("evidence", "upstream_status_raw")})]
    lines += ["## Snapshot provenance",
              ("IT-STE — IT-STE contributors. https://github.com/vladimirmashkov/IT-STE. "
              "Original IT-STE wording and examples only: CC BY-SA 4.0, "
              "https://creativecommons.org/licenses/by-sa/4.0/. "
              "Transformation: deterministic Markdown presentation of draft records; no new approvals."),
              ("ASD-STE100 is owned by Aerospace, Security and Defence Industries Association "
              "of Europe (ASD), https://asd-ste100.org/. Source rights remain separate; "
              "downstream source license is unknown. Derivative permission does not relicense "
              "the source. The source PDF stays private under .local/ and is not included."),
              "Manifest identity and authenticated plan pins:", metadata(manifest)]
    paths = [manifest_path, *(snapshot / name for name in manifest["records"]),
             *(snapshot / name for name in manifest["sources"]), *batch_paths]
    for path in paths:
        lines.append(f"- `{path.relative_to(ROOT).as_posix()}` SHA-256: "
                     f"`{hashlib.sha256(path.read_bytes()).hexdigest()}`")
    for name in manifest["sources"]:
        lines += ["Source record:", metadata(corpus.load_json(snapshot / name))]
    return ("\n\n".join(lines).rstrip() + "\n").encode("utf-8")


def output_path(output):
    requested = Path(output)
    path = requested if requested.is_absolute() else ROOT / requested
    expected = ROOT / DEFAULT_OUTPUT
    if path != expected or any(p.is_symlink() for p in (ROOT, expected.parent, expected)):
        raise DocumentError("Only docs/IT-STE-draft.md is supported; symlinks are forbidden")
    if path.resolve() != ROOT.resolve() / DEFAULT_OUTPUT or not path.parent.is_dir():
        raise DocumentError("Output must stay in the existing repository docs directory")
    return path


def build(output: str | Path = DEFAULT_OUTPUT):
    path = output_path(output)
    data = render()
    if path.exists() and not path.read_bytes().startswith(BANNER.encode("utf-8")):
        raise DocumentError("Refusing to overwrite an unrelated existing file")
    path.write_bytes(data)


def check(output: str | Path = DEFAULT_OUTPUT):
    path = output_path(output)
    expected = render()
    if not path.is_file() or path.read_bytes() != expected:
        raise DocumentError("Generated draft is missing or stale; run build (do not hand-edit)")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    for name in ("build", "check"):
        commands.add_parser(name).add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args(argv)
    try:
        {"build": build, "check": check}[args.command](args.output)
    except (DocumentError, corpus.CorpusError, OSError, ValueError, TypeError, KeyError, ImportError) as error:
        print(f"ERROR: {error}", file=sys.stderr)
        return 2
    print(f"PASS: draft {args.command}; no release or vocabulary approval implied")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
